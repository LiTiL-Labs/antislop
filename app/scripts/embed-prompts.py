#!/usr/bin/env python3
"""Embed the canonical prompt files into AntiSlopCore as Swift string literals.

The canonical, developer-versioned sources stay in ../prompts. Embedding them in
the binary keeps the core prompt internal, avoids loading prompt text from
user-writable locations at runtime, and sidesteps SwiftPM resource bundles in a
hand-assembled .app. `EmbeddedPromptsTests` fails if this file drifts from the
canonical sources; rerun this script after any prompt or profile revision.
"""
from pathlib import Path

app = Path(__file__).resolve().parents[1]
root = app.parent
sources = {
    "primary": root / "prompts" / "primary.md",
    "detect": root / "prompts" / "detect.md",
    "noAISlop": root / "prompts" / "profiles" / "no-ai-slop.md",
    "humanizer": root / "prompts" / "profiles" / "humanizer.md",
    # Upstream MIT notices, shown under Acknowledgements.
    "noAISlopLicense": root / "third_party" / "no-ai-slop" / "LICENSE",
    "humanizerLicense": root / "third_party" / "humanizer" / "LICENSE",
}
out = app / "Sources" / "AntiSlopCore" / "Generated" / "EmbeddedPrompts.swift"

lines = [
    "// GENERATED by app/scripts/embed-prompts.py from ../prompts. Do not edit by hand.",
    "// EmbeddedPromptsTests verifies these literals match the canonical files byte for byte.",
    "",
    "enum EmbeddedPrompts {",
]
for name, path in sources.items():
    text = path.read_text(encoding="utf-8")
    assert '"""##' not in text, f"{path} contains the raw-string terminator"
    assert "\r" not in text, f"{path} contains carriage returns"
    rel = path.relative_to(root)
    lines.append(f"    /// {rel}")
    # A multi-line literal drops the line break before its closing delimiter, so
    # the extra newline preserves the file's final newline exactly.
    lines.append(f'    static let {name} = ##"""')
    lines.append(text + ('"""##' if not text.endswith("\n") else '\n"""##'))
    lines.append("")
lines.append("}")
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {out.relative_to(root)}")
